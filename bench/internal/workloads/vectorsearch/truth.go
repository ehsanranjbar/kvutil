package vectorsearch

import (
	"math"
	"runtime"
	"slices"
	"sync"

	"github.com/ehsanranjbar/kvutil/bench/internal/dataset"
)

// k is the number of nearest documents that every query asks for.
const k = 10

// filter is a condition on the documents that a case puts on the search.
type filter int

const (
	// noFilter asks for the nearest of all the documents.
	noFilter filter = iota
	// rareFilter is lang = 'is', 2% of the documents: kvutil's planner reads the index of the
	// language and ranks what it finds.
	rareFilter
	// broadFilter is year >= 2000, 72% of the documents: kvutil checks the condition on the
	// nearest documents as it goes.
	broadFilter

	numFilters
)

func (f filter) String() string {
	switch f {
	case rareFilter:
		return "rare"
	case broadFilter:
		return "broad"
	}
	return "none"
}

// matches reports whether a document satisfies the filter.
func (f filter) matches(d *dataset.Doc) bool {
	switch f {
	case rareFilter:
		return d.Lang == "is"
	case broadFilter:
		return d.Year >= 2000
	}
	return true
}

// truth is the exact answer to the queries of the pool: for each filter and query the ids of the k
// nearest documents (by the cosine distance, then by id), nearest first. Both systems are scored
// against it, so it is computed in Go and not by either.
type truth struct {
	ids [numFilters][][]int64
}

// neighbour is a document and its distance from a query.
type neighbour struct {
	dist float64
	id   int64
}

func (a neighbour) before(b neighbour) bool {
	return a.dist < b.dist || (a.dist == b.dist && a.id < b.id)
}

// topK keeps the k nearest neighbours that were offered, nearest first.
type topK struct {
	items []neighbour
}

func (t *topK) offer(n neighbour) {
	if len(t.items) == k && !n.before(t.items[k-1]) {
		return
	}
	i, _ := slices.BinarySearchFunc(t.items, n, func(a, b neighbour) int {
		switch {
		case a.before(b):
			return -1
		case b.before(a):
			return 1
		}
		return 0
	})
	if len(t.items) < k {
		t.items = append(t.items, neighbour{})
	}
	copy(t.items[i+1:], t.items[i:])
	t.items[i] = n
}

// dot is the inner product of two vectors of the same length, in float64.
func dot(a, b []float64) float64 {
	b = b[:len(a)]
	var s0, s1, s2, s3 float64
	i := 0
	for ; i+4 <= len(a); i += 4 {
		s0 += a[i] * b[i]
		s1 += a[i+1] * b[i+1]
		s2 += a[i+2] * b[i+2]
		s3 += a[i+3] * b[i+3]
	}
	for ; i < len(a); i++ {
		s0 += a[i] * b[i]
	}
	return (s0 + s1) + (s2 + s3)
}

func widen(v []float32) []float64 {
	out := make([]float64, len(v))
	for i, c := range v {
		out[i] = float64(c)
	}
	return out
}

// computeTruth finds the exact nearest documents of the queries by comparing each with every
// document of ids [0, n), for every filter, on all the CPUs. The documents are generated by each
// worker as it goes, so they are not all in memory at once. The sums are in float64 over the
// float32 components, and the result does not depend on how the documents are shared among the
// workers: the order of the neighbours is total (distance, then id).
func computeTruth(vs *dataset.Vectors, n int, queries [][]float32) *truth {
	qs := make([][]float64, len(queries))
	qnorm := make([]float64, len(queries))
	for i, q := range queries {
		qs[i] = widen(q)
		qnorm[i] = math.Sqrt(dot(qs[i], qs[i]))
	}

	workers := max(1, min(runtime.GOMAXPROCS(0), n))
	parts := make([][numFilters][]topK, workers)
	var wg sync.WaitGroup
	for w := range workers {
		lo, hi := int64(n)*int64(w)/int64(workers), int64(n)*int64(w+1)/int64(workers)
		wg.Add(1)
		go func() {
			defer wg.Done()
			var tops [numFilters][]topK
			for f := range tops {
				tops[f] = make([]topK, len(queries))
			}
			d := &dataset.Doc{}
			for id := lo; id < hi; id++ {
				vs.GenInto(d, id)
				e := widen(d.Embedding)
				enorm := math.Sqrt(dot(e, e))
				for qi, q := range qs {
					nb := neighbour{dist: 1 - dot(e, q)/(enorm*qnorm[qi]), id: id}
					for f := range numFilters {
						if f.matches(d) {
							tops[f][qi].offer(nb)
						}
					}
				}
			}
			parts[w] = tops
		}()
	}
	wg.Wait()

	t := &truth{}
	for f := range numFilters {
		t.ids[f] = make([][]int64, len(queries))
		for qi := range queries {
			var merged topK
			for w := range parts {
				for _, nb := range parts[w][f][qi].items {
					merged.offer(nb)
				}
			}
			ids := make([]int64, len(merged.items))
			for i, nb := range merged.items {
				ids[i] = nb.id
			}
			t.ids[f][qi] = ids
		}
	}
	return t
}

// want is the number of documents that a query of the filter has to find: k, or all of them if the
// filter lets fewer through.
func (t *truth) want(f filter, qi int) int { return len(t.ids[f][qi]) }

// recall is the share of the exact nearest documents of a query that a search found, from 0 to 1.
// A query that has no nearest documents (the filter lets none through) is found whole.
func (t *truth) recall(f filter, qi int, found []int64) float64 {
	exact := t.ids[f][qi]
	if len(exact) == 0 {
		return 1
	}
	hit := 0
	for _, id := range found {
		if slices.Contains(exact, id) {
			hit++
		}
	}
	return float64(hit) / float64(len(exact))
}

// The truth of a dataset is computed once for the process, and shared by the variants.
var (
	truthMu    sync.Mutex
	truthCache = map[truthKey]*truthEntry{}
)

type truthKey struct {
	seed uint64
	n    int
}

type truthEntry struct {
	once    sync.Once
	vectors *dataset.Vectors
	queries [][]float32
	truth   *truth
}

// data is the dataset of a run: the generator, the pool of queries and what their exact answers are.
type data struct {
	n       int
	vectors *dataset.Vectors
	queries [][]float32
	truth   *truth
}

// dataOf returns the dataset for a seed and a number of documents, with the truth computed on the
// first call and shared afterwards.
func dataOf(seed uint64, n int) *data {
	truthMu.Lock()
	e := truthCache[truthKey{seed, n}]
	if e == nil {
		e = &truthEntry{}
		truthCache[truthKey{seed, n}] = e
	}
	truthMu.Unlock()

	e.once.Do(func() {
		e.vectors = dataset.NewVectors(seed, n)
		e.queries = e.vectors.Queries(dataset.QueryPool)
		e.truth = computeTruth(e.vectors, n, e.queries)
	})
	return &data{n: n, vectors: e.vectors, queries: e.queries, truth: e.truth}
}

// describe says what a filter is, for the results.
func (f filter) describe() string {
	switch f {
	case rareFilter:
		return "lang = 'is'"
	case broadFilter:
		return "year >= 2000"
	}
	return "no filter"
}
